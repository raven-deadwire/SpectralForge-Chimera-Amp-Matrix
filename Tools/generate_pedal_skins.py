#!/usr/bin/env python3
"""Procedural board-pedal skins for the PRE expansion models.

Each skin is an original blank stompbox enclosure (paint or metal finish,
bevel, keyline, rubber pad, side jacks) rendered with numpy/Pillow at the
repository's pedal-skin size, written as JPEG (quality 90) plus an 8-bit
alpha PNG like the other skins. No names, logos or controls are drawn: the
plugin overlays its live controls. Deterministic (fixed seeds), so the files
can be regenerated byte-for-byte with the same Pillow/numpy versions.

Usage: python3 Tools/generate_pedal_skins.py [--preview out.png]
"""
import hashlib
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / 'Assets/Artwork'
W, H = 440, 748
BODY = (28, 6, 412, 742)      # enclosure rectangle (x0, y0, x1, y1)
RADIUS = 30

# name, model, finish, base colour, keyline colour (None for none), pad kind,
# knob style, bright face. Finishes: flake, brushed, hammer, matte, gloss.
SKINS = [
    ('pparaeq', 40, 'brushed', (178, 184, 190), (52, 104, 168), 'pad', 'black', True),
    ('pmulticomp', 41, 'hammer', (34, 52, 92), (214, 218, 222), 'pad', 'silver', False),
    ('ptightboost', 42, 'flake', (226, 112, 34), (246, 230, 200), 'pad', 'black', True),
    ('ppowerwah', 43, 'matte', (30, 32, 34), (150, 156, 160), 'treadle', 'silver', False),
    ('pbasssynth', 44, 'flake', (112, 176, 52), (24, 30, 24), 'pad', 'black', True),
    ('pdreadfulperil', 45, 'brushed', (64, 66, 70), (176, 28, 32), 'pad', 'silver', False),
    ('pseveneq', 46, 'gloss', (232, 228, 214), (90, 94, 98), 'pad', 'black', True),
    ('pmultiwah', 47, 'brushed', (104, 108, 114), None, 'treadle', 'silver', False),
    ('poctavefuzz', 48, 'flake', (24, 132, 142), (220, 236, 232), 'pad', 'cream', False),
    ('pvioletrage', 49, 'hammer', (100, 50, 146), (230, 210, 250), 'pad', 'silver', False),
    ('pfiredrake', 50, 'matte', (26, 24, 24), (232, 96, 24), 'pad', 'silver', False),
    ('ppitchbend', 51, 'gloss', (30, 84, 180), None, 'treadle', 'silver', False),
]


def rounded_mask(x0, y0, x1, y1, r):
    """Coverage (anti-aliased) and inward distance to a rounded rectangle."""
    yy, xx = np.mgrid[0:H, 0:W].astype(np.float32) + .5
    hx, hy = (x1 - x0) / 2 - r, (y1 - y0) / 2 - r
    qx, qy = np.abs(xx - (x0 + x1) / 2) - hx, np.abs(yy - (y0 + y1) / 2) - hy
    sdf = np.hypot(np.maximum(qx, 0), np.maximum(qy, 0)) + np.minimum(np.maximum(qx, qy), 0) - r
    return np.clip(.5 - sdf, 0, 1), -sdf


def texture(finish, rng):
    n = rng.standard_normal((H, W)).astype(np.float32)
    if finish == 'brushed':
        # Long vertical strokes: noise averaged along y.
        k = 61
        c = np.cumsum(np.pad(n, ((k, k), (0, 0)), mode='reflect'), axis=0)
        a = (c[2 * k:] - c[:-2 * k])[:H] / (2 * k)
        return (a - a.mean()) / (a.std() + 1e-6) * .05
    if finish == 'hammer':
        low = np.asarray(Image.fromarray(((n * 40) + 128).clip(0, 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(4)), np.float32)
        low = (low - low.mean()) / (low.std() + 1e-6)
        gy, gx = np.gradient(low)
        return .07 * (gx - gy) + .015 * n
    if finish == 'flake':
        sparkle = (rng.random((H, W)) > .985).astype(np.float32) * rng.random((H, W)).astype(np.float32)
        return .03 * n + .25 * sparkle
    if finish == 'gloss':
        return .01 * n
    return .025 * n                                # matte


def shade(base, finish, rng, dist):
    rgb = np.ones((H, W, 3), np.float32) * (np.array(base, np.float32) / 255.)
    t = texture(finish, rng)[..., None]
    rgb = rgb * (1 + t)
    yy, xx = np.mgrid[0:H, 0:W].astype(np.float32)
    # Soft studio light from the top left, a sheen for gloss.
    light = 1.06 - .12 * (yy / H) - .05 * (xx / W)
    if finish == 'gloss':
        light += .18 * np.exp(-((xx - W * .32) / 60.) ** 2)
    rgb *= light[..., None]
    # Bevel: brighter outer rim, darker band just inside it.
    rim = np.clip(1 - dist / 9., 0, 1)
    inner = np.exp(-((dist - 12.) / 4.) ** 2)
    rgb = rgb * (1 + .35 * rim[..., None]) * (1 - .18 * inner[..., None])
    return rgb


def keyline(rgb, colour, inset=20, width=3.0):
    if colour is None:
        return rgb
    x0, y0, x1, y1 = BODY
    _, d = rounded_mask(x0 + inset, y0 + inset, x1 - inset, 500 - 18, RADIUS - 12)
    line = np.exp(-((d - width / 2) / (width / 2)) ** 2) * (d > -1)
    c = np.array(colour, np.float32) / 255.
    return rgb * (1 - line[..., None]) + c * line[..., None]


def pad(rgb, alpha_body, kind, rng):
    x0, _, x1, y1 = BODY
    top = 160 if kind == 'treadle' else 504
    m, d = rounded_mask(x0 + 20, top, x1 - 20, y1 - 24, 18)
    rubber = np.ones((H, W, 3), np.float32) * np.array([42, 44, 47], np.float32) / 255.
    rubber *= (1 + .05 * rng.standard_normal((H, W)).astype(np.float32))[..., None]
    if kind == 'treadle':
        yy = np.mgrid[0:H, 0:W][0].astype(np.float32)
        ridges = .5 + .5 * np.cos((yy - top) / 18. * 2 * np.pi)
        rubber *= (1 - .22 * ridges)[..., None]
    edge = np.clip(1 - d / 5., 0, 1)
    rubber *= (1 + .4 * edge)[..., None]
    shadow = np.exp(-((d + 3) / 4.) ** 2) * (d < 0)
    rgb = rgb * (1 - .45 * shadow[..., None])
    return rgb * (1 - m[..., None]) + rubber * m[..., None]


def jacks(rgb, alpha):
    yy, xx = np.mgrid[0:H, 0:W].astype(np.float32)
    for y in (300,):
        for x0, x1 in ((6, 30), (410, 434)):
            m = ((xx >= x0) & (xx <= x1) & (np.abs(yy - y) <= 15)).astype(np.float32)
            g = .72 + .28 * np.cos((yy - y) / 15. * np.pi / 2)
            metal = np.stack([g * .80, g * .82, g * .85], -1)
            rgb = rgb * (1 - m[..., None]) + metal * m[..., None]
            alpha = np.maximum(alpha, m)
    return rgb, alpha


def render(skin):
    name, model, finish, base, line, kind, _, _ = skin
    rng = np.random.default_rng(model * 7919 + 17)
    alpha, dist = rounded_mask(*BODY, RADIUS)
    rgb = shade(base, finish, rng, dist)
    rgb = keyline(rgb, line)
    rgb = pad(rgb, alpha, kind, rng)
    rgb, alpha = jacks(rgb, alpha)
    rgb = (rgb.clip(0, 1) * 255 + .5).astype(np.uint8)
    a = (alpha.clip(0, 1) * 255 + .5).astype(np.uint8)
    rgb[a == 0] = 0
    return Image.fromarray(rgb, 'RGB'), Image.fromarray(a, 'L')


def main():
    preview = sys.argv[sys.argv.index('--preview') + 1] if '--preview' in sys.argv else None
    records, tiles = [], []
    for skin in SKINS:
        image, alpha = render(skin)
        jpg, png = ART / f'{skin[0]}.jpg', ART / f'{skin[0]}-alpha.png'
        image.save(jpg, quality=90)
        alpha.save(png, optimize=True)
        files = [{'path': str(p.relative_to(ROOT)), 'bytes': p.stat().st_size, 'sha256': hashlib.sha256(p.read_bytes()).hexdigest()} for p in (jpg, png)]
        records.append({'name': skin[0], 'model': skin[1], 'kind': 'pedal', 'generator': 'Tools/generate_pedal_skins.py (procedural)',
                        'finish': skin[2], 'knobStyle': skin[6], 'brightFace': skin[7], 'dimensions': [W, H], 'files': files})
        if preview:
            bg = Image.new('RGB', (W, H), (23, 26, 25)); bg.paste(image, (0, 0), alpha); tiles.append(bg)
    provenance = ART / 'ExpandedArtwork-Provenance.json'
    data = json.loads(provenance.read_text())
    keep = [a for a in data['assets'] if a['name'] not in {r['name'] for r in records}]
    data['assets'] = keep + records
    provenance.write_text(json.dumps(data, indent=2) + '\n')
    if preview:
        sheet = Image.new('RGB', (W * len(tiles), H))
        for i, t in enumerate(tiles):
            sheet.paste(t, (i * W, 0))
        sheet.resize((sheet.width // 2, H // 2)).save(preview)


if __name__ == '__main__':
    main()
