#!/usr/bin/env python3
"""Compile reviewed document identities into the Windows installer.

This is a build tool, never a runtime read of an installed manifest.  Installed
payload-manifest.json is ordinary documentation and is not deletion authority.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = "spectralforge.legacy-document-inventory.v1"
MAX_DOCUMENT_BYTES = 64 * 1024 * 1024


def install_path(path: str) -> str:
    """The historical Inno mapping is intentionally narrower than a tree walk."""
    if not isinstance(path, str) or not path or re.search(r"[\\:'\"*?{}\x00-\x1f]", path):
        raise ValueError(f"unsafe document path: {path!r}")
    parts = path.split("/")
    if any(part in ("", ".", "..") or part != part.rstrip(" .") for part in parts):
        raise ValueError(f"unsafe document path: {path!r}")
    p = PurePosixPath(path)
    if p.is_absolute():
        raise ValueError(f"absolute document path: {path!r}")
    if len(parts) == 1:
        if p.suffix.lower() == ".txt":
            return path
        if p.suffix.lower() in (".md", ".html") or path in ("ARTWORK_PROMPTS.json", "payload-manifest.json"):
            return "Documentation\\" + path
    elif parts[0] == "reference" and p.suffix.lower() in (".json", ".md", ".txt", ".csv"):
        return "Documentation\\" + path.replace("/", "\\")
    raise ValueError(f"not an installer-owned document path: {path!r}")


def is_notice(path: str) -> bool:
    name = PurePosixPath(path).name.upper()
    return any(term in name for term in ("LICENSE", "LICENCE", "COPYING", "NOTICE", "COPYRIGHT"))


def document_rules(inventory: dict, stage: Path) -> list[tuple[str, int, str, bool, bool]]:
    if inventory.get("schema") != SCHEMA:
        raise ValueError("unsupported legacy document inventory schema")
    rules: set[tuple[str, int, str, bool, bool]] = set()
    for entry in inventory["files"]:
        if "windows" not in entry["platforms"]:
            continue
        relative = install_path(entry["path"])
        retire = entry["retire"]
        keep = entry["preserve_always"] or is_notice(entry["path"])
        if not isinstance(retire, bool) or not isinstance(keep, bool) or (retire and keep):
            raise ValueError("license notices cannot be cleanup candidates")
        for variant in entry["variants"]:
            if "windows" not in variant["platforms"]:
                continue
            size, sha = variant["size"], variant["sha256"]
            if type(size) is not int or not 0 <= size <= MAX_DOCUMENT_BYTES:
                raise ValueError("invalid reviewed document size")
            if not isinstance(sha, str) or re.fullmatch(r"[0-9a-f]{64}", sha) is None:
                raise ValueError("invalid reviewed document SHA-256")
            if not variant.get("evidence") or not variant.get("releases"):
                raise ValueError("document identity lacks historical provenance")
            rules.add((relative, size, sha, retire, keep))
    # These are precisely the documentation [Files] entries in Chimera.iss.
    # Never recurse into a personal IR, preset, plugin or arbitrary subdirectory.
    for source in stage.iterdir():
        if source.suffix.lower() not in (".txt", ".md", ".html") and source.name != "payload-manifest.json":
            continue
        if source.is_symlink() or not source.is_file() or source.stat().st_nlink != 1:
            raise ValueError(f"unsafe staged documentation: {source.name}")
        data = source.read_bytes()
        if len(data) > MAX_DOCUMENT_BYTES:
            raise ValueError(f"oversized staged documentation: {source.name}")
        relative = install_path(source.name)
        if any(rule[0].casefold() == relative.casefold() and rule[3] for rule in rules):
            raise ValueError(f"retired research document is still staged: {source.name}")
        rules.add((relative, len(data), hashlib.sha256(data).hexdigest(), False, is_notice(source.name)))
    paths: dict[str, str] = {}
    for path, *_ in rules:
        if path.casefold() in paths and paths[path.casefold()] != path:
            raise ValueError("case-colliding installed document identities")
        paths[path.casefold()] = path
    return sorted(rules)


def render_rules(inventory: dict, stage: Path) -> str:
    lines = [
        "// Generated by Tools/windows_document_rules.py; never trust installed metadata.",
        "procedure LoadDocumentRules;",
        "begin",
    ]
    for path, size, sha, retire, keep in document_rules(inventory, stage):
        lines.append(f"  AddDocumentRule('{path}', {size}, '{sha}', {str(retire)}, {str(keep)});")
    lines.extend(["end;", ""])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--inventory", type=Path, default=ROOT / "Validation/legacy-document-inventory.json")
    parser.add_argument("--stage", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    inventory = json.loads(args.inventory.read_text(encoding="utf-8"))
    text = render_rules(inventory, args.stage)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding="utf-8")
    print(f"Generated Windows document rules: {args.output}")


if __name__ == "__main__":
    main()
